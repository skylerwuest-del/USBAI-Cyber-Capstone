"""Connect CAI's interactive CLI to the managed USB model server."""
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time

from capstone import ROOT, atomic_json
from setup import sha256

CAI = ROOT / "cai"
PYTHON = CAI / "python" / "bin" / "python3.12"


def check_bundle():
    receipt = CAI / "installed.json"
    if not PYTHON.is_file() or not (CAI / "site-packages" / "cai" / "cli.py").is_file() or not receipt.is_file():
        raise RuntimeError("CAI is not installed. Run bash setup-cai.sh, or launch --cai for automatic first-time setup.")
    data = json.loads(receipt.read_text())
    if data.get("cai_version") != "0.5.10" or data.get("lock_sha256") != sha256(ROOT / "cai-requirements.lock"):
        raise RuntimeError("CAI bundle does not match its dependency lock. Run bash setup-cai.sh to repair it.")
    if not os.access(PYTHON, os.X_OK):
        raise RuntimeError("Portable Python is not executable; the USB may be mounted noexec. See README.md.")


def ensure_bundle():
    if not (CAI / "installed.json").is_file():
        print("First CAI launch: installing the USB environment (internet required)...", flush=True)
        try:
            subprocess.run([sys.executable, str(ROOT / "setup_cai.py")], cwd=ROOT, check=True)
        except subprocess.CalledProcessError as exc:
            raise RuntimeError("CAI setup failed. Correct the reported error and rerun bash setup-cai.sh.") from exc
    check_bundle()


def local_settings(config):
    base = "http://127.0.0.1:" + str(config["port"]) + "/v1"
    agent = config.get("cai", {}).get("agent", "one_tool_agent")
    if not isinstance(agent, str) or not re.fullmatch(r"[A-Za-z0-9_]+", agent):
        raise ValueError("config.json cai.agent must be a CAI agent name")
    return {
        "CAI_MODEL": "openai/capstone",
        "CAI_AGENT_TYPE": agent,
        "OPENAI_API_BASE": base,
        "OPENAI_BASE_URL": base,
        "OPENAI_API_KEY": "capstone-local",
        "OLLAMA_API_BASE": base,
        "OLLAMA": "false",
        "CAI_TELEMETRY": "false",
        "CAI_TRACING": "false",
        "OPENAI_AGENTS_DISABLE_TRACING": "1",
        "CAI_MAX_TURNS": "inf",
        "CAI_STREAM": "false",
        "CAI_MEMORY_ONLINE": "false",
        "DO_NOT_TRACK": "1",
        "LITELLM_LOCAL_MODEL_COST_MAP": "True",
        "TIKTOKEN_CACHE_DIR": str(CAI / "cache" / "tiktoken"),
        "HF_HOME": str(CAI / "cache" / "huggingface"),
        "XDG_CACHE_HOME": str(CAI / "cache"),
        "MPLCONFIGDIR": str(CAI / "cache" / "matplotlib"),
        "PYTHONNOUSERSITE": "1",
        "PYTHONDONTWRITEBYTECODE": "1",
        # The managed config below is loaded explicitly in the bootstrap; disable
        # CAI's implicit dotenv discovery so a host/project .env cannot override it.
        "PYTHON_DOTENV_DISABLED": "1",
        "CAPSTONE_CONTEXT_SIZE": str(config["context_size"]),
        "CAPSTONE_MAX_TOKENS": str(config["max_tokens"]),
        "CAPSTONE_REQUEST_TIMEOUT": str(config["request_timeout"]),
    }


def prepare_environment(config):
    settings = local_settings(config)
    atomic_json(CAI / "local-config.json", settings)
    # Human-readable configuration; this contains only a local placeholder key.
    (CAI / ".env.local").write_text("# Generated by CapStone on each launch.\n" +
            "\n".join(key + "=" + json.dumps(value) for key, value in settings.items()) + "\n")
    workdir = ROOT / "workspace" / "cai"
    workdir.mkdir(parents=True, exist_ok=True)
    pricing = {"input_cost_per_token": 0, "output_cost_per_token": 0}
    atomic_json(workdir / "pricing.json", {"openai/capstone": pricing, "capstone": pricing})
    env = dict(os.environ)
    for key in ("PYTHONHOME", "PYTHONPATH", "VIRTUAL_ENV"):
        env.pop(key, None)
    env.update(settings)
    return env, workdir


def run_cai(server, config, prompt=None, smoke=False):
    check_bundle()
    env, workdir = prepare_environment(config)
    server.ensure()
    args = [str(PYTHON), str(ROOT / "cai_bootstrap.py")]
    if smoke:
        args.append("--smoke-test")
    elif prompt is not None:
        args.extend(["--prompt", prompt])
    print("Opening CAI with the selected USB model at " + env["OPENAI_BASE_URL"], flush=True)
    process = subprocess.Popen(args, cwd=workdir, env=env)
    try:
        while process.poll() is None:
            if not server.healthy():
                try:
                    server.ensure()
                except (OSError, RuntimeError) as exc:
                    print("Retrying CAI model server: " + str(exc), flush=True)
            time.sleep(min(config["retry_delay"], 1))
        return process.returncode
    finally:
        # CAI shares the terminal foreground group so prompt_toolkit receives input.
        # Terminate only this owned child; do not signal the parent's process group.
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
